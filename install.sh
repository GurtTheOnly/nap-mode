#!/bin/bash
# install.sh — install the Nap Mode console (font + green/red palette) on any Linux
set -o pipefail

PREFIX=/usr/local
SHARE="$PREFIX/share/nap-mode"
ETC=/etc/nap-mode
HELPER="$PREFIX/bin/nap-console-style"
CLI="$PREFIX/bin/nap-mode"
PALETTE="$ETC/vtrgb"
SNIPPET_DIR="$HOME/.config/nap-mode"
SNIPPET="$SNIPPET_DIR/bash_profile-nap.sh"
SUDOERS=/etc/sudoers.d/nap-mode

APPLY_TTY=""
LOGIN_HOOK=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --tty) APPLY_TTY="${2:-2}"; shift 2 ;;
    --tty=*) APPLY_TTY="${1#*=}"; shift ;;
    --login-hook) LOGIN_HOOK=1; shift ;;
    -h|--help)
      echo "Usage: sudo ./install.sh [--tty N] [--login-hook]"
      echo "  --tty N        Apply font+palette to ttyN after install (default 2)"
      echo "  --login-hook   Auto-apply the palette on every login shell on tty2"
      exit 0 ;;
    *) echo "install.sh: unknown option: $1" >&2; exit 1 ;;
  esac
done

if [[ $(id -u) -ne 0 ]]; then
  echo "install.sh: run as root — sudo ./install.sh" >&2
  exit 1
fi

SELF_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

echo "Installing Nap Mode console style..."
install -d -m 0755 "$ETC"
install -D -m 0644 "$SELF_DIR/share/vtrgb" "$PALETTE"
install -D -m 0644 "$SELF_DIR/share/vtrgb" "$SHARE/vtrgb"
install -D -m 0755 "$SELF_DIR/bin/nap-console-style" "$HELPER"
install -D -m 0755 "$SELF_DIR/bin/nap-mode" "$CLI"

if [[ $LOGIN_HOOK -eq 1 ]]; then
  echo "Setting up login hook for ${SUDO_USER:-$USER}..."
  install -d -m 0755 "$SNIPPET_DIR"
  cat > "$SNIPPET" <<EOF
# >>> nap-mode >>> (auto-generated by nap-mode install.sh)
# Apply the green/red console palette whenever a login shell starts on tty2.
if [[ -z \${WAYLAND_DISPLAY:-} && "\${XDG_VTNR:-}" == "2" ]]; then
  sudo -n /usr/local/bin/nap-console-style 2 >/dev/null 2>&1 || true
fi
# <<< nap-mode <<<
EOF
  chown "${SUDO_USER:-$USER}" "$SNIPPET" 2>/dev/null || true
  chmod 0644 "$SNIPPET"

  USER_NAME="${SUDO_USER:-$USER}"
  USER_HOME=$(getent passwd "$USER_NAME" | cut -d: -f6)
  if [[ -f "$USER_HOME/.bash_profile" ]]; then
    if ! grep -q 'nap-mode >>>' "$USER_HOME/.bash_profile" 2>/dev/null; then
      echo "Adding snippet to $USER_HOME/.bash_profile"
      printf '\n. "%s"\n' "$SNIPPET" >> "$USER_HOME/.bash_profile"
      chown "$USER_NAME" "$USER_HOME/.bash_profile" 2>/dev/null || true
    fi
  elif [[ -f "$USER_HOME/.profile" ]]; then
    if ! grep -q 'nap-mode >>>' "$USER_HOME/.profile" 2>/dev/null; then
      echo "Adding snippet to $USER_HOME/.profile"
      printf '\n. "%s"\n' "$SNIPPET" >> "$USER_HOME/.profile"
      chown "$USER_NAME" "$USER_HOME/.profile" 2>/dev/null || true
    fi
  else
    echo "No .bash_profile/.profile found for $USER_NAME — add manually:"
    echo "  echo '. ~/.config/nap-mode/bash_profile-nap.sh' >> ~/.bash_profile"
  fi

  if [[ ! -f "$SUDOERS" ]]; then
    echo "Adding passwordless sudoers rule for nap-console-style..."
    cat > "$SUDOERS" <<EOF
# nap-mode: allow the user to set the VT font/palette without a password
$USER_NAME ALL=(root) NOPASSWD: /usr/local/bin/nap-console-style
EOF
    if visudo -cf "$SUDOERS" >/dev/null 2>&1; then
      chmod 0440 "$SUDOERS"
    else
      echo "install.sh: sudoers file failed validation — removing" >&2
      rm -f "$SUDOERS"
    fi
  fi
fi

echo
echo "Installed:"
echo "  helper:  $HELPER"
echo "  CLI:     $CLI"
echo "  palette: $PALETTE"

if command -v setfont >/dev/null 2>&1; then
  echo "  font:    detected console font (terminus-family)"
else
  echo "  font:    setfont not found — install 'kbd' (Arch) or 'kbd' (Debian/Ubuntu)"
fi

if [[ -n $APPLY_TTY ]]; then
  echo "Applying style to tty$APPLY_TTY..."
  "$HELPER" "$APPLY_TTY" || echo "warning: apply failed (see above)" >&2
fi

echo
echo "Next steps:"
echo "  1. sudo nap-console-style 2      # apply font+palette now"
echo "  2. Ctrl+Alt+F2                   # switch to the nap console"
echo "  3. Ctrl+Alt+F1                   # return to the GUI"
echo "  4. nap-mode colors               # show the palette as swatches"